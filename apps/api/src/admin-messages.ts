// Without a saved choice, the first English or German entry of Accept-Language wins.
export const preferredLanguage = (header: string | undefined): Language => {
  for (const part of (header ?? '').split(',')) {
    const tag = part.trim().slice(0, 2).toLowerCase();
    if (tag === 'en' || tag === 'de') return tag;
  }
  return 'en';
};
